"""Generate Zod validators and inferred TS types from authoritative JSON schemas."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def compile_schema(value, root):
    if '$ref' in value:
        target = root
        for part in value['$ref'].removeprefix('#/').split('/'):
            target = target[part]
        return compile_schema(target, root)
    if 'enum' in value:
        if len(value['enum']) == 1:
            return 'z.literal(' + json.dumps(value['enum'][0]) + ')'
        return 'z.union([' + ','.join('z.literal(' + json.dumps(v) + ')' for v in value['enum']) + '])'
    if 'const' in value:
        return 'z.literal(' + json.dumps(value['const']) + ')'
    kind = value.get('type')
    if isinstance(kind, list):
        return 'z.union([' + ','.join(compile_schema({**value, 'type': item}, root) for item in kind) + '])'
    if kind == 'object':
        if not value.get('properties'):
            return 'z.record(z.unknown())'
        fields = []
        for name, child in value['properties'].items():
            expression = compile_schema(child, root)
            if name not in value.get('required', []):
                expression += '.optional()'
            fields.append(json.dumps(name) + ':' + expression)
        return 'z.object({' + ',\n'.join(fields) + '})' + ('.strict()' if value.get('additionalProperties') is False else '.passthrough()')
    if kind == 'array':
        result = 'z.array(' + compile_schema(value.get('items', {}), root) + ')'
        for key, method in [('minItems', 'min'), ('maxItems', 'max')]:
            if key in value:
                result += f'.{method}({value[key]})'
        return result
    result = {'string': 'z.string()', 'number': 'z.number().finite()', 'integer': 'z.number().int()',
              'boolean': 'z.boolean()', 'null': 'z.null()'}.get(kind, 'z.unknown()')
    for key, method in [('minLength', 'min'), ('maxLength', 'max'), ('minimum', 'min'), ('maximum', 'max')]:
        if key in value and ((kind == 'string' and key in {'minLength', 'maxLength'}) or (kind in {'number', 'integer'} and key in {'minimum', 'maximum'})):
            result += f'.{method}({value[key]})'
    if 'pattern' in value:
        result += '.regex(new RegExp(' + json.dumps(value['pattern']) + '))'
    if value.get('format') == 'date-time':
        result += '.datetime({offset:true})'
    return result


def generated():
    text = '// Generated by scripts/generate_ui_contracts.py. Edit shared contracts only through their review gate.\nimport { z } from "zod";\n'
    def emit(name, filename, selector=None):
        nonlocal text
        root = json.loads((ROOT / 'shared/contracts' / filename).read_text())
        value = root if selector is None else selector(root)
        text += f'export const {name}Schema = ' + compile_schema(value, root) + ';\n'
        text += f'export type {name} = z.infer<typeof {name}Schema>;\n'
    for name, filename in [('CanonicalWorkflow', 'workflow-schema-v1.json'), ('CanonicalAgent', 'agent-contract-v1.json'),
                           ('CanonicalTool', 'tool-contract-v1.json'), ('SafeError', 'error-format-v1.json'), ('AuthContext', 'auth-permissions-v1.json')]:
        emit(name, filename)
    for name, key in [('ApiRequest', 'request_envelope'), ('ApiResponse', 'response_envelope'), ('Collection', 'collection_response')]:
        emit(name, 'api-payloads-v1.json', lambda root, key=key: root['properties'][key])
    emit('Operation', 'api-payloads-v1.json', lambda root: root['properties']['operation_names']['items'])
    emit('RunEvent', 'run-status-versioning-v1.json', lambda root: root['properties']['run_event'])
    emit('RunStatus', 'run-status-versioning-v1.json', lambda root: root['properties']['run_states']['items'])
    emit('RevisionStatus', 'run-status-versioning-v1.json', lambda root: root['properties']['workflow_revision_states']['items'])
    return text


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'frontend/src/api/contracts.generated.ts'
    contents = generated()
    if args.check:
        if not target.exists() or target.read_text() != contents:
            raise SystemExit('Generated UI contracts are stale. Run python3 scripts/generate_ui_contracts.py.')
        print('Generated UI contracts match canonical schemas.')
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(contents)
