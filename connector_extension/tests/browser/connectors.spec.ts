import { test, expect } from "../../../frontend/node_modules/@playwright/test/index.mjs";
for (const mobile of [false, true]) {
  test(`extension discovery and approved connector execution on ${mobile ? "mobile" : "desktop"}`, async ({ page }) => {
    if (mobile) await page.setViewportSize({ width: 390, height: 844 });
    const errors: string[] = [];
    page.on("pageerror", error => errors.push(error.message));

    await page.goto("/app/integrations");
    await page.getByText("Test Google tools with a workflow",{exact:true}).click();
    const operations=page.getByLabel("Google test operation",{exact:true});
    await expect(operations.locator('option[value="extension_calendar_create"]')).toHaveCount(1);
    const catalog=await page.request.get("/api/backend/tools");
    expect(catalog.status(),await catalog.text()).toBe(200);
    const tools=(await catalog.json()).data.items;
    expect(tools).toHaveLength(20);
    expect(tools.map((tool:{tool_id:string})=>tool.tool_id)).toEqual(expect.arrayContaining(["extension_mail_attachment","extension_calendar_create"]));
    const config=await page.request.post('/api/backend/integrations/google_sheets/test',{data:{mode:'configuration'}});
    expect(config.status(),await config.text()).toBe(200);
    expect((await config.json()).data.tested).toBe(false);
    await expect(page.getByText("Verified",{exact:true})).toHaveCount(0);
    await page.goto("/app/workflows");
    await page.getByRole("button", { name: "Actions for Extension Calendar smoke" }).click();
    await page.getByRole("menuitem", { name: "Run published" }).click();
    await page.getByRole("dialog").getByRole("button",{name:"Start run",exact:true}).click();
    await expect(page.getByText(/Run run_.* · paused_for_approval/)).toBeVisible();
    await page.goto("/app/approvals");
    const run = page.getByRole("button", { name: /extension_calendar_browser/ }).first();
    await expect(run).toBeVisible();
    await run.click();
    await page.getByRole("button", { name: "Approve", exact: true }).click();
    await expect(page.getByText(/Approval approval_.* · approved · v1/)).toBeVisible();
    await page.goto("/app/runs");
    await expect(page.getByRole("button", { name: /completed.*extension_calendar_browser/ }).first()).toBeVisible();
    await page.goto("/app");
    const link = `https://docs.google.com/spreadsheets/d/new_project_book_${mobile?"mobile":"desktop"}/edit`;
    await page.getByLabel("Process description").fill(`Read ${link}, discover tabs and headers, and summarize the requirements.`);
    await page.getByRole("button", { name: "Generate workflow", exact: true }).click();
    await expect(page).toHaveURL(/\/app\/workflows\/planned_/);
    const workflowId=new URL(page.url()).pathname.split("/").at(-1)!;
    await page.getByRole("button", { name: "Prepare & Activate", exact: true }).click();
    await expect.poll(async () => {
      const overview = await page.request.get("/api/backend/workflow-overview");
      const item = (await overview.json()).data.items.find((row: { workflow_id: string }) => row.workflow_id === workflowId);
      return item?.activation_state;
    }).toBe("active");
    await page.goto("/app/workflows");
    await page.locator(`a[href="/app/workflows/${workflowId}"]`).first().locator("..").getByRole("button",{name:"Actions for New spreadsheet check"}).click();
    await page.getByRole("menuitem", { name: "Run published" }).click();
    await page.getByRole("dialog").getByRole("button",{name:"Start run",exact:true}).click();
    await expect(page.getByText(/Run run_.* · completed/)).toBeVisible();
    const response = await page.request.get("/api/backend/workflows");
    const document = (await response.json()).data.items.find((workflow: { workflow_id: string }) => workflow.workflow_id === workflowId);
    expect(document.nodes.find((node: { kind: string }) => node.kind === "tool").configuration.input.spreadsheet_url).toBe(link);
    const runDialog=page.getByRole("dialog");
    await runDialog.getByRole("button",{name:"Close",exact:true}).first().click();
    await expect(runDialog).toHaveCount(0);
    await page.getByRole("button", { name: "Actions for Extension Mail smoke" }).click();
    await page.getByRole("menuitem", { name: "Run published" }).click();
    await page.getByRole("dialog").getByRole("button",{name:"Start run",exact:true}).click();
    await expect(page.getByText(/Run run_.* · paused_for_approval/)).toBeVisible();
    await page.goto("/app/approvals");
    await page.getByRole("button", { name: /extension_mail_browser/ }).first().click();
    await page.getByRole("button", { name: "Approve", exact: true }).click();
    await expect(page.getByText(/Approval approval_.* · approved · v1/)).toBeVisible();
    await page.goto("/app/runs");
    await expect(page.getByRole("button", { name: /completed.*extension_mail_browser/ }).first()).toBeVisible();
    expect(errors).toEqual([]);
  });
}
