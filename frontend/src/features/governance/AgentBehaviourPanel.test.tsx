import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { AgentBehaviourPanel } from './AgentBehaviourPanel';
import { DEFAULT_AGENT_BEHAVIOUR } from '@/domain/agent-behaviour';
import { useMesh } from '@/domain/store';
beforeEach(()=>useMesh.setState({agentBehaviourPreferences:structuredClone(DEFAULT_AGENT_BEHAVIOUR)}));
afterEach(cleanup);
it('keeps unapplied selections local and persists only preferences when applied',()=>{
 const agents=useMesh.getState().agents; const workflows=useMesh.getState().workflows;
 render(<AgentBehaviourPanel policies={[]} onViewLimits={()=>{}}/>);
 expect(screen.getAllByRole('switch')).toHaveLength(8);
 fireEvent.click(screen.getByRole('button',{name:'Professional'}));
 expect(screen.getByRole('switch',{name:'Formal tone'})).toBeChecked();
 expect(useMesh.getState().agentBehaviourPreferences.formalTone).toBe(false);
 fireEvent.click(screen.getByRole('switch',{name:'Preferred language'}));
 fireEvent.change(screen.getByLabelText('Response language'),{target:{value:'Hindi'}});
 expect(screen.getByRole('button',{name:'Professional'})).toHaveAttribute('aria-pressed','false');
 fireEvent.click(screen.getByRole('button',{name:/^Strict$/}));
 expect(screen.getByRole('switch',{name:'Screen abusive language'})).toBeChecked();
 expect(screen.getByRole('switch',{name:'Require supporting evidence'})).toBeChecked();
 fireEvent.click(screen.getByRole('button',{name:'Strict format'}));
 expect(screen.getByRole('switch',{name:'Strict output format'})).toBeChecked();
 fireEvent.click(screen.getByRole('button',{name:'Apply preferences'}));
 expect(screen.getByRole('status')).toHaveTextContent('Preferences saved in this browser.');
 expect(useMesh.getState().agentBehaviourPreferences.language).toBe('Hindi');
 expect(useMesh.getState().agents).toBe(agents); expect(useMesh.getState().workflows).toBe(workflows);
 const stored=JSON.parse(localStorage.getItem('mesh-local-drafts-v1')!);
 expect(stored.state.agentBehaviourPreferences.language).toBe('Hindi');
 cleanup(); render(<AgentBehaviourPanel policies={[]} onViewLimits={()=>{}}/>);
 expect(screen.getByLabelText('Response language')).toHaveValue('Hindi');
});
it('opens the existing limits view and reports storage failure without success',()=>{
 const navigate=vi.fn(); render(<AgentBehaviourPanel policies={[]} onViewLimits={navigate}/>);
 fireEvent.click(screen.getByRole('button',{name:'View all limits'}));expect(navigate).toHaveBeenCalledOnce();
 fireEvent.click(screen.getByRole('button',{name:'Concise'}));
 const apply=vi.spyOn(useMesh.getState(),'applyAgentBehaviourPreferences').mockImplementation(()=>{window.dispatchEvent(new Event('mesh-draft-storage-error'));});
 cleanup(); render(<AgentBehaviourPanel policies={[]} onViewLimits={navigate}/>);
 fireEvent.click(screen.getByRole('button',{name:'Concise'}));fireEvent.click(screen.getByRole('button',{name:'Apply preferences'}));
 expect(screen.getByRole('alert')).toHaveTextContent('could not be saved');expect(screen.queryByRole('status')).toBeNull();apply.mockRestore();
});
